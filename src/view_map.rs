//! Compact project map: the default `context` view. A short quoted purpose,
//! then a typed, directed connection map grouped by source node — each source
//! printed once with its human name and reference, followed by short target
//! lists per connection type. Only confirmed edges are listed; mentions,
//! requested/failed accesses and name-match candidates are counted and shown
//! only with `--weak`, in their own block. Evidence and "why" live in `expand`;
//! the previous section view stays available as `context --detailed`.

use super::*;
use crate::relations;
use std::collections::{BTreeSet, HashSet};

/// Default byte budget of the compact map (whole lines only).
pub const DEFAULT_BUDGET: usize = 4000;
/// Smallest accepted `--budget` for the map.
pub const MIN_BUDGET: usize = 600;
/// Targets printed per connection type of one source before `+N`.
pub const MAX_TARGETS: usize = 6;

/// Map-specific options next to the shared [`MapLimits`].
#[derive(Clone, Debug)]
pub struct MapOpts {
    pub budget: usize,
    pub weak: bool,
}

impl Default for MapOpts {
    fn default() -> Self {
        MapOpts { budget: DEFAULT_BUDGET, weak: false }
    }
}

/// Connection type of a stored edge and whether it is weak (unconfirmed).
/// `None`: containment/bookkeeping rows the map does not show.
pub fn classify(kind: &str, strength: &str) -> Option<(&'static str, bool)> {
    let t = match (kind, strength) {
        ("read", "observed") => ("read", false),
        ("write", "observed") => ("write", false),
        ("read", "parsed") => ("parsed-read", false),
        ("write", "parsed") => ("parsed-write", false),
        ("read", "requested") => ("read-requested", true),
        ("write", "requested") => ("write-requested", true),
        ("read", _) => ("read-failed", true),
        ("write", _) => ("write-failed", true),
        ("mentioned", _) => ("mention", true),
        ("searched", _) => ("searched", true),
        ("listed", _) => ("listed", true),
        ("references", _) => ("ref", false),
        ("reference_candidate", _) => ("ref-candidate", true),
        ("touched", _) => ("changes", false),
        ("history", _) => ("history", false),
        (k, class) if k.starts_with("rel:") => match class {
            "declared" => ("dependency", false),
            "structural" => ("symlink", false),
            "documented" => ("ref", false),
            "observed" => ("co-use", false),
            "identity" => ("same-upstream", false),
            "hash" => ("same-content", false),
            _ => ("name-match", true),
        },
        _ => return None,
    };
    Some(t)
}

