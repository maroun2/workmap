/// Generic template/boilerplate intros that do not state a purpose.
const TEMPLATE_MARKERS: &[&str] = &[
    "bootstrapped with",
    "this template should help",
    "this template provides",
    "generated by create-",
    "created with create-",
    "getting started with",
    "welcome to your new",
    "a short description",
    "project description",
    "add your description",
    "describe your project",
    "lorem ipsum",
    "todo: ",
    "replace this",
    "your project name",
];

/// True when an intro line is generic template text rather than the project's own purpose.
pub fn is_template(text: &str) -> bool {
    let l = text.to_lowercase();
    let t = l.trim();
    t == "todo" || t == "tbd" || TEMPLATE_MARKERS.iter().any(|m| l.contains(m))
}

const INTRO_SQL: &str = "SELECT line, text FROM excerpts WHERE node_id=?1 AND text NOT LIKE '![%' AND text NOT LIKE '[![%' AND text NOT LIKE '<%' AND text NOT LIKE '---%' ORDER BY line LIMIT 1";

/// `Purpose …` line: the first intro sentence of the first doc (README first)
/// whose intro is not template text, quoted with path and line; else the
/// hosting catalog description; else an honest "not stated".
pub fn purpose_line(c: &Connection, p: &Project, docs: &[Node]) -> R<String> {
    let co = &p.focus;
    let top = p.top(co);
    let mut template: Option<(String, i64, String)> = None;
    for d in docs.iter().filter(|d| d.kind == "doc") {
        // The file as it is now; the indexed excerpt when it is gone.
        let intro = match d.path.as_deref().and_then(|x| crate::util::read_head(Path::new(x), 64 << 10).ok()) {
            Some(bytes) => intro_line(&String::from_utf8_lossy(&bytes)),
            None => db(c.query_row(INTRO_SQL, [&d.id], |r| Ok((r.get(0)?, r.get(1)?))).map(Some).or_else(|e| if matches!(e, rusqlite::Error::QueryReturnedNoRows) { Ok(None) } else { Err(e) }))?,
        };
        let Some((line, text)) = intro else { continue };
        let relp = node_rel(d, &top);
        if is_template(&text) {
            template.get_or_insert((relp, line, text));
            continue;
        }
        return Ok(format!("Purpose ({} l.{line}): \"{}\"\n", fref(p, co, &relp), clip(&first_sentence(&text), 140)));
    }
    if let Some(d) = p.repo.meta.pointer("/catalog/description").and_then(|x| x.as_str()).filter(|d| !d.trim().is_empty()) {
        let prov = p.repo.meta.pointer("/catalog/provider").and_then(|x| x.as_str()).unwrap_or("remote");
        return Ok(format!("Purpose ({prov} repository description): \"{}\"\n", clip(d, 140)));
    }
    Ok(match template {
        Some((relp, line, text)) => format!("Purpose: not stated; {} l.{line} is generic template text (\"{}\")\n", fref(p, co, &relp), clip(&text, 60)),
        None => "Purpose: not stated (no README/doc intro indexed in this worktree)\n".into(),
    })
}

/// First prose line of a Markdown/text doc: `(line, text)`, skipping front
/// matter, headings, code fences, badges/images, HTML, tables and rules.
pub fn intro_line(text: &str) -> Option<(i64, String)> {
    let mut in_fence = false;
    let mut in_front = false;
    for (i, raw) in text.lines().enumerate() {
        let l = raw.trim();
        if i == 0 && l == "---" {
            in_front = true;
            continue;
        }
        if in_front {
            in_front = l != "---" && l != "...";
            continue;
        }
        if l.starts_with("```") || l.starts_with("~~~") {
            in_fence = !in_fence;
            continue;
        }
        let markup = ["#", "![", "[![", "<", "|", "---", "***", "===", "[//]:"].iter().any(|p| l.starts_with(p));
        // Lines made only of links/badges carry no prose.
        let only_links = l.starts_with('[') && l.ends_with(')') && l.contains("](") && l.chars().filter(|c| c.is_alphabetic()).count() < 40;
        if in_fence || l.is_empty() || markup || only_links {
            continue;
        }
        return Some(((i + 1) as i64, crate::util::redact(&clip(l, 220))));
    }
    None
}

/// First sentence of a paragraph line (keeps the whole line when no sentence end).
fn first_sentence(t: &str) -> String {
    let b = t.as_bytes();
    for (i, ch) in t.char_indices() {
        if matches!(ch, '.' | '!' | '?') && (i + 1 == t.len() || b.get(i + 1) == Some(&b' ')) && i >= 20 {
            return t[..=i].to_string();
        }
    }
    t.to_string()
}

/// A node printed in the map: reference (already shell-quoted when needed).
struct Pick {
    id: String,
    r: String,
}

/// Outgoing edges of `src` with their target node, ordered deterministically.
fn out_edges(c: &Connection, src: &str) -> R<Vec<(String, String, String, Node)>> {
    let mut st = db(c.prepare(
        "SELECT e.kind, e.strength, e.dst, n.id, n.kind, n.label, n.path, n.repo_id, n.checkout_id, n.ts, n.meta FROM edges e JOIN nodes n ON n.id=e.dst WHERE e.src=?1 ORDER BY e.kind, e.strength, n.path, n.id",
    ))?;
    let rows = db(st.query_map([src], |r| {
        let n = Node {
            id: r.get(3)?,
            kind: r.get(4)?,
            label: r.get(5)?,
            path: r.get(6)?,
            repo_id: r.get(7)?,
            checkout_id: r.get(8)?,
            ts: r.get::<_, Option<i64>>(9)?.unwrap_or(0),
            meta: serde_json::from_str(&r.get::<_, String>(10)?).unwrap_or(Value::Null),
        };
        Ok((r.get::<_, String>(0)?, r.get::<_, String>(1)?, r.get::<_, String>(2)?, n))
    }))?;
    db(rows.collect())
}

/// Count of confirmed (non-weak, shown) edges touching each node of a checkout.
fn strong_degree(c: &Connection, co: &str) -> R<HashMap<String, usize>> {
    let mut deg: HashMap<String, usize> = HashMap::new();
    for side in ["dst", "src"] {
        let sql = format!("SELECT e.{side}, e.kind, e.strength, count(*) FROM edges e JOIN nodes n ON n.id=e.{side} WHERE n.checkout_id=?1 AND n.kind IN ('file','doc','memory') GROUP BY 1,2,3");
        let mut st = db(c.prepare(&sql))?;
        let rows: Vec<(String, String, String, i64)> = db(db(st.query_map([co], |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?, r.get(3)?))))?.collect::<Result<_, _>>())?;
        for (id, k, s, n) in rows {
            if matches!(classify(&k, &s), Some((_, false))) {
                *deg.entry(id).or_default() += n as usize;
            }
        }
    }
    Ok(deg)
}

/// Per session of the project: (confirmed out-edges, weak out-edges).
fn session_degrees(c: &Connection, repo: &str) -> R<HashMap<String, (usize, usize)>> {
    let mut st = db(c.prepare("SELECT e.src, e.kind, e.strength, count(*) FROM edges e JOIN nodes s ON s.id=e.src WHERE s.kind='session' AND s.repo_id=?1 GROUP BY 1,2,3"))?;
    let rows: Vec<(String, String, String, i64)> = db(db(st.query_map([repo], |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?, r.get(3)?))))?.collect::<Result<_, _>>())?;
    let mut m: HashMap<String, (usize, usize)> = HashMap::new();
    for (id, k, s, n) in rows {
        match classify(&k, &s) {
            Some((_, false)) => m.entry(id).or_default().0 += n as usize,
            Some((_, true)) => m.entry(id).or_default().1 += n as usize,
            None => {}
        }
    }
    Ok(m)
}

/// Grouped adjacency of one source: `(type, targets shown, hidden count)` per type.
type Adj = Vec<(&'static str, Vec<String>, usize)>;

/// Render `  read, write → a, b +3` lines; types with identical target lists share a line.
fn adj_lines(adj: &Adj, arrow: &str) -> Vec<String> {
    let mut merged: Vec<(Vec<&str>, &Vec<String>, usize)> = Vec::new();
    for (t, targets, more) in adj {
        if let Some(m) = merged.iter_mut().find(|m| m.1 == targets && m.2 == *more) {
            m.0.push(t);
        } else {
            merged.push((vec![t], targets, *more));
        }
    }
    merged
        .into_iter()
        .map(|(ts, targets, more)| {
            let line = match (targets.is_empty(), more) {
                (true, n) => format!("+{n}"),
                (false, 0) => targets.join(", "),
                (false, n) => format!("{} +{n}", targets.join(", ")),
            };
            format!("  {} {arrow} {line}", ts.join(", "))
        })
        .collect()
}

/// Group of output lines that is kept or dropped as a whole under the budget.
struct Group {
    cat: usize,
    lines: Vec<String>,
}

pub fn compact_map(v: &View, p: &Project, lim: &MapLimits, opts: &MapOpts) -> R<String> {
    let c = v.c;
    let co = &p.focus;
    let top = p.top(co);
    let mut pc = ProjectCache::new(c);

    // ---- candidates per category (all within the project / focused worktree scope)
    let docs = db(nodes(
        c,
        "kind IN ('doc','memory') AND checkout_id=?1 ORDER BY kind, (label NOT LIKE '%README%'), (label NOT LIKE '%CLAUDE%' AND label NOT LIKE '%AGENTS%'), length(label), label",
        &[&co.id],
    ))?;
    let deg = strong_degree(c, &co.id)?;
    let d = |id: &str| deg.get(id).copied().unwrap_or(0);
    let mut doc_order: Vec<(usize, &Node)> = docs.iter().enumerate().filter(|(_, n)| d(&n.id) > 0).collect();
    doc_order.sort_by(|a, b| d(&b.1.id).cmp(&d(&a.1.id)).then(a.0.cmp(&b.0)));
    let sel_docs: Vec<&Node> = doc_order.iter().take(lim.docs).map(|x| x.1).collect();

    let top_of: BTreeMap<String, String> = p.checkouts.iter().map(|n| (n.id.clone(), n.path.clone().unwrap_or_default())).collect();
    let ranked = db(rank_files(c, std::slice::from_ref(&co.id), &top_of))?;
    let files_total = ranked.iter().filter(|r| r.node.kind == "file").count();
    let sel_files: Vec<&Node> = ranked.iter().map(|r| &r.node).filter(|n| n.kind == "file" && d(&n.id) > 0).take(lim.files).collect();

    let all = sessions_of(c, p)?;
    let sdeg = session_degrees(c, &p.repo.id)?;
    let mut convs: Vec<&Node> = all.iter().filter(|s| sdeg.get(&s.id).map(|x| x.0).unwrap_or(0) > 0).collect();
    convs.sort_by(|a, b| b.ts.cmp(&a.ts).then(a.id.cmp(&b.id)));
    let sel_convs: Vec<&Node> = convs.iter().take(lim.sessions).copied().collect();

    let commits = db(nodes(c, "kind='commit' AND id IN (SELECT dst FROM edges WHERE src=?1 AND kind='history') ORDER BY ts DESC, id", &[&co.id]))?;
    let picked_targets: HashSet<&str> = sel_docs.iter().chain(sel_files.iter()).map(|n| n.id.as_str()).collect();
    let mut commit_hits: Vec<(usize, usize, &Node)> = Vec::new();
    for (i, cm) in commits.iter().enumerate() {
        let n: i64 = db(c.query_row("SELECT count(*) FROM edges WHERE src=?1 AND kind='touched'", [&cm.id], |r| r.get(0)))?;
        if n == 0 {
            continue;
        }
        let hits = out_edges(c, &cm.id)?.iter().filter(|e| e.0 == "touched" && picked_targets.contains(e.2.as_str())).count();
        commit_hits.push((hits, i, cm));
    }
    commit_hits.sort_by(|a, b| b.0.cmp(&a.0).then(a.1.cmp(&b.1)));
    let sel_commits: Vec<&Node> = commit_hits.iter().take(lim.commits).map(|x| x.2).collect();

    let rels = db(relations::neighbors(c, &p.repo.id))?;
    let mut rel_by: BTreeMap<String, Vec<&relations::Rel>> = BTreeMap::new();
    for r in rels.iter().filter(|r| !r.is_candidate()) {
        rel_by.entry(r.to.clone()).or_default().push(r);
    }
    let mut rel_rows: Vec<(&String, &Vec<&relations::Rel>)> = rel_by.iter().collect();
    rel_rows.sort_by_key(|(id, rs)| (rs.iter().map(|r| more::class_rank(&r.class)).min().unwrap_or(9), relations::node_name(c, id)));
    let sel_rel: Vec<(&String, &Vec<&relations::Rel>)> = rel_rows.into_iter().take(lim.related).collect();
    let weak_rel = rels.iter().filter(|r| r.is_candidate()).count();

    // ---- references of selected nodes
    let mut picks: Vec<Pick> = Vec::new();
    for n in sel_docs.iter().chain(sel_files.iter()) {
        picks.push(Pick { id: n.id.clone(), r: fref(p, co, &node_rel(n, &top)) });
    }
    let selected: HashMap<&str, usize> = picks.iter().enumerate().map(|(i, x)| (x.id.as_str(), i)).collect();
    let mut shown: BTreeSet<String> = BTreeSet::new();
    let mut weak_hidden = if opts.weak { 0 } else { weak_rel };
    let mut weak_groups: Vec<Group> = Vec::new();

    // Target reference: selected node, or a file/doc outside the focused worktree
    // (sibling worktree or other project, fully qualified); None = in-scope but not selected.
    let target_ref = |n: &Node, pc: &mut ProjectCache| -> Option<String> {
        if let Some(&i) = selected.get(n.id.as_str()) {
            return Some(picks[i].r.clone());
        }
        if !matches!(n.kind.as_str(), "file" | "doc" | "memory") || n.checkout_id.as_deref() == Some(co.id.as_str()) {
            return None;
        }
        if let Some(x) = co_of(p, n.checkout_id.as_deref()) {
            return Some(fref(p, x, &node_rel(n, &p.top(x))));
        }
        let oco = n.checkout_id.as_deref().and_then(|id| get_node(c, id).ok().flatten())?;
        let (op, _) = pc.get(oco.repo_id.as_deref()?)?;
        let op = Project { repo: op.repo.clone(), handle: op.handle.clone(), checkouts: op.checkouts.clone(), focus: oco.clone() };
        Some(q(&qualified_raw(&op, &oco, &node_rel(n, oco.path.as_deref().unwrap_or("")))))
    };

    // Build adjacency of one source over its outgoing edges.
    // `local_only`: commit nodes are shared by every checkout of the repository, so
    // their `touched` rows also point at the same paths in sibling worktrees; a
    // commit listed under this worktree's history keeps only this worktree's files.
    let build = |src: &str, local_only: bool, pc: &mut ProjectCache, shown: &mut BTreeSet<String>| -> R<(Adj, Adj, usize)> {
        let mut strong: Vec<(&'static str, Vec<(usize, String)>, usize)> = Vec::new();
        let mut weak: Vec<(&'static str, Vec<(usize, String)>, usize)> = Vec::new();
        let mut nweak = 0;
        let mut seen: HashSet<(&'static str, String)> = HashSet::new();
        for (kind, strength, dst, n) in out_edges(c, src)? {
            let Some((t, is_weak)) = classify(&kind, &strength) else { continue };
            if t == "history" || (local_only && n.checkout_id.as_deref() != Some(co.id.as_str())) {
                continue;
            }
            if !seen.insert((t, dst.clone())) {
                continue;
            }
            if is_weak {
                nweak += 1;
            }
            let bucket = if is_weak { &mut weak } else { &mut strong };
            let i = match bucket.iter().position(|b| b.0 == t) {
                Some(i) => i,
                None => {
                    bucket.push((t, vec![], 0));
                    bucket.len() - 1
                }
            };
            match target_ref(&n, pc) {
                Some(r) => {
                    // Selected targets in selection order first, then outside-scope ones.
                    let rank = selected.get(n.id.as_str()).copied().unwrap_or(usize::MAX);
                    bucket[i].1.push((rank, r));
                }
                None => bucket[i].2 += 1,
            }
        }
        let fin = |b: Vec<(&'static str, Vec<(usize, String)>, usize)>, shown: &mut BTreeSet<String>, record: bool| -> Adj {
            let mut out: Adj = Vec::new();
            let order = |t: &str| LEGEND.iter().position(|l| l.0 == t).unwrap_or(99);
            let mut b = b;
            b.sort_by_key(|x| order(x.0));
            for (t, mut targets, more) in b {
                targets.sort();
                targets.dedup_by(|a, b| a.1 == b.1);
                let extra = targets.len().saturating_sub(MAX_TARGETS);
                let list: Vec<String> = targets.into_iter().take(MAX_TARGETS).map(|x| x.1).collect();
                if record {
                    shown.extend(list.iter().cloned());
                }
                if !list.is_empty() || more > 0 {
                    out.push((t, list, more + extra));
                }
            }
            out
        };
        // Types whose targets are all outside the selection still show as `+N`.
        let s = fin(strong, shown, true);
        let w = fin(weak, shown, false);
        Ok((s, w, nweak))
    };

    let mut groups: Vec<Group> = Vec::new();
    let mut used_types: BTreeSet<&'static str> = BTreeSet::new();

    // Category 0: project relations (direction kept per row: → this project's row points at it).
    if !sel_rel.is_empty() {
        let mut fwd: Vec<(&'static str, Vec<String>, usize)> = Vec::new();
        let mut back: Vec<(&'static str, Vec<String>, usize)> = Vec::new();
        for (id, rs) in &sel_rel {
            let name = q(&format!(":related:{}", relations::node_name(c, id)));
            let mut kinds: BTreeSet<(bool, &'static str)> = BTreeSet::new();
            for r in rs.iter() {
                if let Some((t, false)) = classify(&format!("rel:{}", r.kind), &r.class) {
                    kinds.insert((r.forward, t));
                }
            }
            for (f, t) in kinds {
                used_types.insert(t);
                let side = if f { &mut fwd } else { &mut back };
                match side.iter_mut().find(|x| x.0 == t) {
                    Some(x) => x.1.push(name.clone()),
                    None => side.push((t, vec![name.clone()], 0)),
                }
            }
        }
        let order = |t: &str| LEGEND.iter().position(|l| l.0 == t).unwrap_or(99);
        fwd.sort_by_key(|x| order(x.0));
        back.sort_by_key(|x| order(x.0));
        let mut lines = vec![format!("{} (this project)", q(&p.handle))];
        lines.extend(adj_lines(&fwd, "→"));
        lines.extend(adj_lines(&back, "←"));
        groups.push(Group { cat: 0, lines });
    }

    // Name-match candidates between projects: unconfirmed, listed only with --weak.
    if opts.weak && weak_rel > 0 {
        let mut fwd: BTreeMap<&'static str, BTreeSet<String>> = BTreeMap::new();
        let mut back: BTreeMap<&'static str, BTreeSet<String>> = BTreeMap::new();
        for r in rels.iter().filter(|r| r.is_candidate()) {
            if let Some((t, true)) = classify(&format!("rel:{}", r.kind), &r.class) {
                used_types.insert(t);
                let name = q(&format!(":related:{}", relations::node_name(c, &r.to)));
                if r.forward { &mut fwd } else { &mut back }.entry(t).or_default().insert(name);
            }
        }
        let mut wl = vec![format!("{} (this project)", q(&p.handle))];
        for (side, arrow) in [(fwd, "→"), (back, "←")] {
            let adj: Adj = side.into_iter().map(|(t, names)| (t, names.into_iter().collect(), 0)).collect();
            wl.extend(adj_lines(&adj, arrow));
        }
        weak_groups.push(Group { cat: 5, lines: wl });
    }

    // Category 1: worktree history → selected commits.
    if !sel_commits.is_empty() {
        used_types.insert("history");
        let refs: Vec<String> = sel_commits.iter().map(|n| commit_ref(meta(n, "sha"))).collect();
        let more = commits.len().saturating_sub(refs.len());
        let adj: Adj = vec![("history", refs, more)];
        let mut lines = vec![format!("worktree {}", worktree_name(p, co))];
        lines.extend(adj_lines(&adj, "→"));
        groups.push(Group { cat: 1, lines });
    }

    // Category 2: conversations (title + stable session-id reference).
    for s in &sel_convs {
        let (adj, wadj, nweak) = build(&s.id, false, &mut pc, &mut shown)?;
        weak_hidden += if opts.weak { 0 } else { nweak };
        let wt = co_of(p, s.checkout_id.as_deref()).map(|x| worktree_name(p, x)).unwrap_or_else(|| "?".into());
        let pre = more::session_prefix(&all, s);
        let r = if pre.is_empty() { conv_ref(&all, s) } else { q(&format!(":session:{pre}")) };
        let head = format!("\"{}\" {r} ({}@{wt} {})", clip(&s.label, 60), meta(s, "provider"), day(s.ts));
        adj.iter().for_each(|a| {
            used_types.insert(a.0);
        });
        let mut lines = vec![head.clone()];
        lines.extend(adj_lines(&adj, "→"));
        groups.push(Group { cat: 2, lines });
        if opts.weak && !wadj.is_empty() {
            wadj.iter().for_each(|a| {
                used_types.insert(a.0);
            });
            let mut wl = vec![head];
            wl.extend(adj_lines(&wadj, "→"));
            weak_groups.push(Group { cat: 5, lines: wl });
        }
    }

    // Category 3: docs as sources (references to files).
    for n in &sel_docs {
        let (adj, wadj, nweak) = build(&n.id, false, &mut pc, &mut shown)?;
        weak_hidden += if opts.weak { 0 } else { nweak };
        let r = picks[selected[n.id.as_str()]].r.clone();
        if !adj.is_empty() {
            adj.iter().for_each(|a| {
                used_types.insert(a.0);
            });
            let mut lines = vec![r.clone()];
            lines.extend(adj_lines(&adj, "→"));
            groups.push(Group { cat: 3, lines });
            shown.insert(r.clone());
        }
        if opts.weak && !wadj.is_empty() {
            wadj.iter().for_each(|a| {
                used_types.insert(a.0);
            });
            let mut wl = vec![r];
            wl.extend(adj_lines(&wadj, "→"));
            weak_groups.push(Group { cat: 5, lines: wl });
        }
    }

    // Category 4: commits (changes).
    for n in &sel_commits {
        let (adj, _, _) = build(&n.id, true, &mut pc, &mut shown)?;
        adj.iter().for_each(|a| {
            used_types.insert(a.0);
        });
        let subject = n.label.split_once(' ').map(|x| x.1).unwrap_or(&n.label);
        let mut lines = vec![format!("{} \"{}\" ({})", commit_ref(meta(n, "sha")), clip(subject, 60), day(n.ts))];
        lines.extend(adj_lines(&adj, "→"));
        groups.push(Group { cat: 4, lines });
    }

    // Selected docs/files whose edges all lead outside the selection.
    let isolated: Vec<String> = picks.iter().filter(|x| !shown.contains(&x.r)).map(|x| x.r.clone()).collect();

    // ---- header (always printed)
    let mut o = String::new();
    let head = meta(co, "head");
    let dirty = co.path.as_deref().and_then(|x| crate::git::dirty_count(Path::new(x)));
    let _ = writeln!(
        o,
        "# {} — map · {} @ {top} · HEAD {} · {} modified · last commit {}",
        p.handle,
        worktree_name(p, co),
        &head[..head.len().min(8)],
        dirty.map(|x| x.to_string()).unwrap_or_else(|| "?".into()),
        day(co.ts)
    );
    o.push_str(&purpose_line(c, p, &docs)?);
    o.push_str(&crate::trust::index_line(c));
    let cov = crate::trust::coverage(c, Some(&p.repo.id));
    if cov.truncated + cov.capped + cov.missing + cov.with_warnings > 0 {
        o.push_str(&crate::trust::coverage_line(&cov));
    }
    let mut vars = vec![format!("WORKMAP_PROJECT={}", q(&p.handle))];
    if !p.is_default(co) {
        vars.push(format!("WORKMAP_WORKTREE={}", q(&worktree_name(p, co))));
    }
    if !v.state.is_empty() {
        vars.push(v.state.clone());
    }
    let _ = writeln!(o, "Scope: export {} — `:` refs are relative to it; other worktrees/projects are fully qualified", vars.join(" "));
    if p.checkouts.len() > 1 {
        let names: Vec<String> = p.checkouts.iter().map(|x| format!("{}{}{}", worktree_name(p, x), if x.id == co.id { "*" } else { "" }, if is_missing(x) { " (missing)" } else { "" })).collect();
        let _ = writeln!(o, "Worktrees ({}): {}", p.checkouts.len(), names.join(", "));
    }
    let _ = writeln!(
        o,
        "Selected (confirmed edges only): docs {}/{} · files {}/{} · conversations {}/{} · commits {}/{} · projects {}/{} · weak edges hidden: {}",
        sel_docs.len(),
        docs.len(),
        sel_files.len(),
        files_total,
        sel_convs.len(),
        all.len(),
        sel_commits.len(),
        commits.len(),
        sel_rel.len(),
        rel_by.len(),
        if opts.weak {
            "none (--weak)".to_string()
        } else if weak_hidden > 0 {
            format!("{weak_hidden} (--weak shows them)")
        } else {
            "0".into()
        }
    );
    // Types sharing a meaning print together: `read/write = tool result recorded`.
    let mut legend: Vec<(Vec<&str>, &str)> = Vec::new();
    for (t, what) in LEGEND.iter().filter(|l| used_types.contains(l.0)) {
        match legend.iter_mut().find(|x| x.1 == *what) {
            Some(x) => x.0.push(t),
            None => legend.push((vec![t], what)),
        }
    }
    if !legend.is_empty() {
        let l: Vec<String> = legend.iter().map(|(ts, what)| format!("{} = {what}", ts.join("/"))).collect();
        let _ = writeln!(o, "Types (A type → B: stored edge from A to B; ← from B to A; +N: more targets, see expand A): {}", l.join("; "));
    }

    // ---- body: round-robin over categories, whole groups, within the budget
    let mut ordered: Vec<&Group> = Vec::new();
    let max_cat = 6;
    let mut cursors = vec![0usize; max_cat];
    let by_cat: Vec<Vec<&Group>> = (0..max_cat).map(|k| groups.iter().filter(|g| g.cat == k).collect()).collect();
    loop {
        let mut any = false;
        for k in 0..max_cat {
            if let Some(g) = by_cat[k].get(cursors[k]) {
                ordered.push(g);
                cursors[k] += 1;
                any = true;
            }
        }
        if !any {
            break;
        }
    }
    let iso = (!isolated.is_empty()).then(|| Group { cat: 9, lines: vec![format!("Also selected (not listed above): {}", isolated.join(", "))] });
    let weak_head = (!weak_groups.is_empty()).then(|| Group { cat: 5, lines: vec!["Unconfirmed (--weak; NOT evidence of access or relation):".to_string()] });

    let mut more_flags: Vec<String> = Vec::new();
    if doc_order.len() > sel_docs.len() {
        more_flags.push(format!("--docs {}", doc_order.len()));
    }
    let files_conn = ranked.iter().filter(|r| r.node.kind == "file" && d(&r.node.id) > 0).count();
    if files_conn > sel_files.len() {
        more_flags.push(format!("--files {}", (lim.files * 3).min(files_conn)));
    }
    if convs.len() > sel_convs.len() {
        more_flags.push(format!("--sessions {}", (lim.sessions * 3).min(convs.len())));
    }
    if commit_hits.len() > sel_commits.len() {
        more_flags.push(format!("--commits {}", (lim.commits * 3).min(commit_hits.len())));
    }
    let mut next = format!("\nNext: {cmd} expand REF (evidence, details) · {cmd} search 'words' · {cmd} context --detailed (sections view)", cmd = v.cmd);
    if !more_flags.is_empty() {
        let _ = write!(next, " · more: {cmd} context {}", more_flags.join(" "), cmd = v.cmd);
    }
    next.push('\n');

    let mut body = String::new();
    if groups.is_empty() {
        let _ = writeln!(body, "\nNo confirmed connections indexed for this worktree; start with: {} search 'words' --project {}", v.cmd, q(&p.handle));
    }
    let tail: Vec<&Group> = iso.iter().chain(weak_head.iter()).chain(weak_groups.iter()).collect();
    let mut dropped_groups = 0usize;
    let mut dropped_lines = 0usize;
    let reserve = next.len() + 120;
    let mut first = true;
    for g in ordered.into_iter().chain(tail) {
        let text: String = g.lines.iter().map(|l| format!("{l}\n")).collect();
        let sep = if first { "\n" } else { "" };
        if dropped_groups == 0 && o.len() + body.len() + sep.len() + text.len() + reserve <= opts.budget {
            body.push_str(sep);
            body.push_str(&text);
            first = false;
        } else {
            dropped_groups += 1;
            dropped_lines += g.lines.len();
        }
    }
    o.push_str(&body);
    if dropped_groups > 0 {
        let _ = writeln!(o, "… {dropped_groups} more group(s), {dropped_lines} line(s) omitted at --budget {} bytes (raise --budget, or use --detailed)", opts.budget);
    }
    o.push_str(&next);
    Ok(o)
}
