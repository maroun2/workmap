//! `install`: copy the binary into per-provider home skills, write SKILL.md with a
//! bounded overview, and a user-level systemd timer for a daily scan.
//! Idempotent; never uses sudo; never writes through symlinked skill dirs.

use crate::config::Env;
use rusqlite::Connection;
use std::path::{Path, PathBuf};

pub const SEED: &str = "Use before exploring an unfamiliar project or repeating an investigation. Discover related work you may not know exists: files, worktrees, commits, and previous agent conversations. Find who already investigated a problem, search past conversation messages, see related projects with evidence, and ask follow-up questions using their saved context. Indexed projects: ";
pub const MAX_DESCRIPTION: usize = 1000;
pub const MAX_BODY: usize = 24 * 1024;

pub struct InstallOpts {
    pub activate: bool,
}

/// Skill directories per provider, relative to home.
pub const SKILL_DIRS: &[(&str, &str)] = &[("claude", ".claude/skills"), ("codex", ".codex/skills"), ("opencode", ".config/opencode/skills")];

fn write_if_changed(path: &Path, data: &[u8]) -> std::io::Result<bool> {
    if std::fs::read(path).map(|d| d == data).unwrap_or(false) {
        return Ok(false);
    }
    if let Some(d) = path.parent() {
        std::fs::create_dir_all(d)?;
    }
    let tmp = path.with_extension("workmap-tmp");
    std::fs::write(&tmp, data)?;
    std::fs::rename(&tmp, path)?;
    Ok(true)
}

fn set_exec(path: &Path) -> std::io::Result<()> {
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o755))
}

/// Refuse targets reached through a symlink or living inside a Git checkout
/// (e.g. a skills dir that is a shared repo).
pub fn unsafe_target(home: &Path, dir: &Path) -> Option<String> {
    let rel = dir.strip_prefix(home).ok()?;
    let mut cur = home.to_path_buf();
    for comp in rel.components() {
        cur.push(comp);
        match std::fs::symlink_metadata(&cur) {
            Ok(m) if m.file_type().is_symlink() => return Some(format!("{} is a symlink", cur.display())),
            Ok(_) => {
                if cur.join(".git").exists() {
                    return Some(format!("{} is inside a git checkout", cur.display()));
                }
            }
            Err(_) => break, // will be created
        }
    }
    None
}

pub fn description(c: &Connection) -> String {
    let mut labels: Vec<String> = Vec::new();
    if let Ok(mut st) = c.prepare("SELECT label FROM nodes WHERE kind='repo' ORDER BY ts DESC, label") {
        if let Ok(rows) = st.query_map([], |r| r.get::<_, String>(0)) {
            labels = rows.flatten().collect();
        }
    }
    let mut d = SEED.to_string();
    let mut shown = 0;
    for l in &labels {
        let piece = if shown == 0 { l.clone() } else { format!(", {l}") };
        if d.len() + piece.len() + 16 > MAX_DESCRIPTION {
            break;
        }
        d.push_str(&piece);
        shown += 1;
    }
    if shown < labels.len() {
        d.push_str(&format!(" (+{} more)", labels.len() - shown));
    }
    if labels.is_empty() {
        d.push_str("(none yet; run workmap scan)");
    }
    d.push('.');
    let remote: i64 = c.query_row("SELECT count(*) FROM nodes WHERE kind='remote'", [], |r| r.get(0)).unwrap_or(0);
    let extra = format!(" Plus {remote} accessible remote repositories not cloned here.");
    if remote > 0 && d.len() + extra.len() <= MAX_DESCRIPTION {
        d.push_str(&extra);
    }
    d
}

/// Ownership marker: only files carrying it are ever rewritten by `refresh_skills`.
pub const MARKER: &str = "<!-- generated by workmap install; refreshed after each scan -->";

use crate::util::sh_quote;

/// `env WORKMAP_STATE_DIR=… [WORKMAP_HOME=…] <bin>` so generated commands use the same index.
pub fn command_prefix(env: &Env, bin: &Path) -> String {
    let vars: Vec<String> = env.exports().iter().map(|(k, v)| sh_quote(&format!("{k}={v}"))).collect();
    format!("env {} {}", vars.join(" "), sh_quote(&bin.display().to_string()))
}

pub fn skill_body(c: &Connection, env: &Env, bin: &Path) -> String {
    let b = command_prefix(env, bin);
    let mut o = format!(
        "{MARKER}\n\n# workmap\n\nLocal index of Git repos, worktrees, docs, commits and native agent conversations (Claude Code, Codex, OpenCode). Output lists evidence with source paths, lines and timestamps; it does not decide what is authoritative.\n\n\
         ## Commands\n\nPick a project from the overview below, then set the scope once and use short references:\n\n```\n{b} overview                                   # all indexed projects by name\nexport WORKMAP_PROJECT=<project>             # or add --project <project> to each command; WORKMAP_WORKTREE=<branch> for a non-main worktree\n{b} context                                    # project map: docs, key files, commits, conversations, related projects\n{b} context --task 'what you are doing' --file <path> --budget 6000   # ranked context for a task; every item says why\n{b} search 'words'                             # full text over docs, commits, conversation messages (all projects, or scoped with --project)\n{b} related                                    # related projects with evidence (manifests, submodules, symlinks, doc links, shared files)\n{b} why <project> <other>                      # shortest evidence chain between two projects\n{b} expand :<path>                             # conversations that read/wrote a file, docs naming it, commits\n{b} expand ':<doc>#<heading-slug>'             # one doc section, quoted from the file\n{b} expand :commit:<sha-prefix>                # one commit\n{b} expand ':conversation:<title prefix>'      # one agent conversation and its file accesses (:session:<id-prefix> also works)\n{b} ask ':conversation:<title prefix>' 'question' --dry-run   # read-only resume plan; drop --dry-run to run\n{b} scan                                       # refresh (incremental; also refreshes this file)\n```\n\nOutput is evidence (paths, lines, timestamps), not interpretation. Conversation text is historical; a latest user input is not a decision. Check the `Index:` line for staleness and `Coverage:` for truncated or missing transcripts. Entries marked remote: are repositories you can access but have not cloned (metadata; doc text only when remote snapshots are enabled, at a recorded commit, never local disk).\n\n"
    );
    o.push_str(&format!(
        "## Registering project roots (do this once after install)\n\nThe default scan walks {} (symlinks followed two levels deep; caches, `.config`, `.local`, `tmp` skipped). Ask the user which directories hold their projects, and also look for project locations named in their agent configs, shell history or the repos listed below. Register every root directory outside that walk, then rescan:\n\n```\n{b} roots list\n{b} roots add <dir>          # repeat per project root\n{b} scan\n```\n\nRegistered roots:\n",
        env.home.display()
    ));
    let roots = env.load_roots();
    if roots.is_empty() {
        o.push_str("- (none yet)\n");
    }
    for r in roots {
        o.push_str(&format!("- {}\n", r.display()));
    }
    o.push_str("\n## Indexed overview\n\n");
    // Drop the scan clock from the header so an unchanged index renders byte-identical.
    let ov = crate::overview::overview(c, 40, &b).unwrap_or_default();
    let ov: Vec<String> = ov.lines().enumerate().map(|(i, l)| if i == 0 { l.split("; last scan").next().unwrap_or(l).to_string() } else { l.to_string() }).collect();
    o.push_str(&ov.join("\n"));
    o.push('\n');
    let v = crate::view::View { c, cmd: b.clone(), state: String::new() };
    let lim = crate::view::MapLimits { docs: 3, files: 4, commits: 2, sessions: 2, related: 3 };
    if let Ok(mut st) = c.prepare("SELECT id FROM nodes WHERE kind='repo' ORDER BY ts DESC LIMIT 8") {
        let ids: Vec<String> = st.query_map([], |r| r.get(0)).map(|r| r.flatten().collect()).unwrap_or_default();
        for id in ids {
            if o.len() > MAX_BODY {
                o.push_str(&format!("\n… truncated; run `{b} context <project>` for the rest.\n"));
                break;
            }
            if let Ok(p) = crate::view::resolve_project(c, &id) {
                o.push('\n');
                o.push_str(&crate::view::project_map(&v, &p, &lim).unwrap_or_default().replacen("# ", "### ", 1).replace("\n## ", "\n#### "));
            }
        }
    }
    if o.len() > MAX_BODY + 4096 {
        let mut cut = MAX_BODY + 4096;
        while !o.is_char_boundary(cut) {
            cut -= 1;
        }
        o.truncate(cut);
        o.push_str("\n… truncated\n");
    }
    o
}

pub fn render_skill(c: &Connection, env: &Env, bin: &Path) -> String {
    format!("---\nname: workmap\ndescription: {}\n---\n\n{}", yaml_quote(&description(c)), skill_body(c, env, bin))
}

/// After a scan: rewrite existing, workmap-owned SKILL.md files only. Never
/// creates targets, copies binaries, or touches systemd.
pub fn refresh_skills(env: &Env, c: &Connection) -> std::io::Result<Vec<String>> {
    let mut report = Vec::new();
    for (provider, rel) in SKILL_DIRS {
        let dir: PathBuf = env.home.join(rel).join("workmap");
        let skill = dir.join("SKILL.md");
        if std::fs::symlink_metadata(&skill).is_err() {
            continue; // not installed there: nothing to refresh
        }
        if let Some(why) = unsafe_target(&env.home, &skill) {
            report.push(format!("skipped {provider} skill refresh: {why}"));
            continue;
        }
        let current = std::fs::read_to_string(&skill).unwrap_or_default();
        if !current.starts_with("---\nname: workmap\n") || !current.contains(MARKER) {
            report.push(format!("skipped {provider} skill refresh: {} not generated by workmap", skill.display()));
            continue;
        }
        let bin = dir.join("bin/workmap");
        if !bin.is_file() {
            report.push(format!("skipped {provider} skill refresh: {} missing (run workmap install)", bin.display()));
            continue;
        }
        let changed = write_if_changed(&skill, render_skill(c, env, &bin).as_bytes())?;
        report.push(format!("{} {provider} skill {}", if changed { "refreshed" } else { "unchanged" }, skill.display()));
    }
    Ok(report)
}

fn yaml_quote(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

pub fn units(env: &Env, bin: &Path) -> (String, String) {
    let envs: String = env.exports().iter().map(|(k, v)| format!("Environment=\"{k}={}\"\n", v.replace('\\', "\\\\").replace('"', "\\\""))).collect();
    let service = format!("[Unit]\nDescription=workmap daily index scan\n\n[Service]\nType=oneshot\n{envs}ExecStart={} scan --quiet\nNice=10\nIOSchedulingClass=idle\n", bin.display());
    let timer = "[Unit]\nDescription=Run workmap scan daily\n\n[Timer]\nOnCalendar=daily\nPersistent=true\nRandomizedDelaySec=15min\n\n[Install]\nWantedBy=timers.target\n".to_string();
    (service, timer)
}

/// Remove what `install` wrote: copied binaries, workmap-owned skills and the
/// user timer. The index (state dir) is kept and its path printed.
pub fn uninstall(env: &Env) -> std::io::Result<Vec<String>> {
    let mut report = Vec::new();
    let unit_dir = env.home.join(".config/systemd/user");
    if !env.overridden && std::env::var_os("XDG_RUNTIME_DIR").is_some() && unit_dir.join("workmap-scan.timer").exists() {
        let ok = std::process::Command::new("systemctl").args(["--user", "disable", "--now", "workmap-scan.timer"]).status().map(|s| s.success()).unwrap_or(false);
        report.push(format!("systemctl --user disable --now workmap-scan.timer: {}", if ok { "ok" } else { "FAILED" }));
    }
    for f in ["workmap-scan.service", "workmap-scan.timer"] {
        let p = unit_dir.join(f);
        if p.is_file() && std::fs::read_to_string(&p).map(|t| t.contains("workmap")).unwrap_or(false) {
            std::fs::remove_file(&p)?;
            report.push(format!("removed {}", p.display()));
        }
    }
    for (provider, rel) in SKILL_DIRS {
        let dir = env.home.join(rel).join("workmap");
        if !dir.exists() {
            continue;
        }
        if let Some(why) = unsafe_target(&env.home, &dir) {
            report.push(format!("left {provider} skill alone: {why}"));
            continue;
        }
        let owned = std::fs::read_to_string(dir.join("SKILL.md")).map(|t| t.contains(MARKER)).unwrap_or(false);
        if !owned {
            report.push(format!("left {} alone: not generated by workmap", dir.display()));
            continue;
        }
        std::fs::remove_dir_all(&dir)?;
        report.push(format!("removed {provider} skill {}", dir.display()));
    }
    let share = env.home.join(".local/share/workmap");
    if share.is_dir() && unsafe_target(&env.home, &share).is_none() {
        std::fs::remove_dir_all(&share)?;
        report.push(format!("removed {}", share.display()));
    }
    let _ = std::fs::remove_file(env.state_dir.join("installed"));
    report.push(format!("kept the index at {} — delete that directory to remove all indexed data", env.state_dir.display()));
    Ok(report)
}

pub fn install(env: &Env, c: &Connection, self_exe: &Path, opts: &InstallOpts) -> std::io::Result<Vec<String>> {
    let mut report = Vec::new();
    let exe = std::fs::read(self_exe)?;
    let canonical_bin = env.home.join(".local/share/workmap/bin/workmap");
    let ch = write_if_changed(&canonical_bin, &exe)?;
    set_exec(&canonical_bin)?;
    report.push(format!("{} {}", if ch { "wrote" } else { "unchanged" }, canonical_bin.display()));
    for (provider, rel) in SKILL_DIRS {
        let dir: PathBuf = env.home.join(rel).join("workmap");
        if let Some(why) = unsafe_target(&env.home, &dir) {
            report.push(format!("skipped {provider} skill: {why}; not writing through shared/linked skill dirs"));
            continue;
        }
        let bin = dir.join("bin/workmap");
        let ch = write_if_changed(&bin, &exe)?;
        set_exec(&bin)?;
        let skill = render_skill(c, env, &bin);
        let ch2 = write_if_changed(&dir.join("SKILL.md"), skill.as_bytes())?;
        report.push(format!("{} {} skill at {}", if ch || ch2 { "updated" } else { "unchanged" }, provider, dir.display()));
    }
    let unit_dir = env.home.join(".config/systemd/user");
    if let Some(why) = unsafe_target(&env.home, &unit_dir) {
        report.push(format!("skipped systemd units: {why}"));
    } else {
        let (svc, tim) = units(env, &canonical_bin);
        let a = write_if_changed(&unit_dir.join("workmap-scan.service"), svc.as_bytes())?;
        let b = write_if_changed(&unit_dir.join("workmap-scan.timer"), tim.as_bytes())?;
        report.push(format!("{} systemd user units in {}", if a || b { "wrote" } else { "unchanged" }, unit_dir.display()));
        if opts.activate && !env.overridden && std::env::var_os("XDG_RUNTIME_DIR").is_some() {
            let ok = |args: &[&str]| std::process::Command::new("systemctl").arg("--user").args(args).status().map(|s| s.success()).unwrap_or(false);
            let r = ok(&["daemon-reload"]) && ok(&["enable", "--now", "workmap-scan.timer"]);
            report.push(format!("systemctl --user enable --now workmap-scan.timer: {}", if r { "ok" } else { "FAILED" }));
        } else {
            report.push("timer not activated (fake home, --no-activate, or no user session bus)".into());
        }
    }
    std::fs::create_dir_all(&env.state_dir)?;
    write_if_changed(&env.state_dir.join("installed"), b"1\n")?;
    report.push(format!("next: register every project root outside {} with `workmap roots add <dir>`, then `workmap scan` (the skill lists this step for agents)", env.home.display()));
    Ok(report)
}
